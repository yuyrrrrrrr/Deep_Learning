
import torch
import torch.nn as nn
import matplotlib.pyplot as plt

# ============================================================
# 一、准备数据：模拟短视频用户兴趣预测任务
# ============================================================

# 固定随机种子，方便重复实验
torch.manual_seed(42)

# 每个样本包含 4 个特征：
# [视频时长、作者粉丝数特征、是否点赞、观看时段特征]
# 为了方便训练，所有特征都控制在 0~1 范围内
样本数量 = 1000
特征数量 = 4

X = torch.rand(样本数量, 特征数量)

# 构造模拟的真实兴趣分数，范围为 0~1
# 这里人为设计一个规律，让模型有目标可学习
真实分数 = (
    0.25 * X[:, 0]
    + 0.35 * X[:, 1]
    + 0.25 * X[:, 2]
    + 0.15 * X[:, 3]
)

# 增加少量噪声，模拟真实数据的不确定性
噪声 = 0.02 * torch.randn(样本数量)

# 将真实分数限制在 0~1
y = (真实分数 + 噪声).clamp(0, 1).reshape(-1, 1)

print("输入数据形状：", X.shape)  # [1000, 4]
print("目标数据形状：", y.shape)  # [1000, 1]


# ============================================================
# 二、定义神经网络
# ============================================================

class 兴趣预测网络(nn.Module):
    def __init__(self):
        super().__init__()

        # 第一层：4 个输入特征 -> 16 个隐藏神经元
        self.隐藏层 = nn.Linear(4, 16)

        # 第二层：16 个隐藏神经元 -> 1 个预测值
        self.输出层 = nn.Linear(16, 1)

        # 使用 ReLU 激活函数，引入非线性
        self.激活函数 = nn.ReLU()

        # 初始化隐藏层权重：He 初始化，适合 ReLU
        nn.init.kaiming_normal_(
            self.隐藏层.weight,
            nonlinearity="relu"
        )

        # 将隐藏层偏置初始化为 0
        nn.init.zeros_(self.隐藏层.bias)

        # 初始化输出层权重
        nn.init.xavier_uniform_(self.输出层.weight)

        # 将输出层偏置初始化为 0
        nn.init.zeros_(self.输出层.bias)

    def forward(self, x):
        # 前向传播第一步：线性变换 z = Wx + b
        z1 = self.隐藏层(x)

        # 前向传播第二步：经过 ReLU 激活函数
        a1 = self.激活函数(z1)

        # 前向传播第三步：计算最终预测值
        prediction = self.输出层(a1)

        return prediction


# 创建神经网络实例
model = 兴趣预测网络()

print("\n神经网络结构：")
print(model)


# ============================================================
# 三、定义损失函数和优化器
# ============================================================

# 使用均方误差衡量预测值与真实值的差距
loss_function = nn.MSELoss()

# 使用 Adam 优化器，根据梯度更新权重和偏置
optimizer = torch.optim.Adam(
    model.parameters(),
    lr=0.01
)

# 学习率 lr 决定参数更新的步幅


# ============================================================
# 四、开始训练
# ============================================================

训练轮数 = 100
批次大小 = 32

# 用于保存每一轮的平均损失，方便后续绘图
损失记录 = []

for epoch in range(训练轮数):

    # 每一轮打乱样本顺序，避免模型总以相同顺序读取数据
    indices = torch.randperm(样本数量)

    本轮损失总和 = 0.0

    # 每次取一个批次的数据进行训练
    for start in range(0, 样本数量, 批次大小):

        # 获取当前批次的索引
        batch_indices = indices[start:start + 批次大小]

        # 取出当前批次的输入和真实答案
        batch_X = X[batch_indices]
        batch_y = y[batch_indices]

        # ----------------------------------------------------
        # 第 1 步：清空上一次计算留下的梯度
        # PyTorch 默认会累积梯度，因此每次更新前需要清空
        # ----------------------------------------------------
        optimizer.zero_grad()

        # ----------------------------------------------------
        # 第 2 步：前向传播
        # 输入经过隐藏层、ReLU、输出层，得到预测值
        # ----------------------------------------------------
        prediction = model(batch_X)

        # ----------------------------------------------------
        # 第 3 步：计算损失
        # 比较预测值和真实值，衡量当前模型的误差
        # ----------------------------------------------------
        loss = loss_function(prediction, batch_y)

        # ----------------------------------------------------
        # 第 4 步：反向传播
        # 自动微分根据链式法则计算各参数的梯度
        # 例如：损失对隐藏层权重的偏导数
        # ----------------------------------------------------
        loss.backward()

        # 第一次训练时，查看梯度是如何产生的
        if epoch == 0 and start == 0:
            print("\n第一次反向传播：")
            print(
                "隐藏层权重梯度形状：",
                model.隐藏层.weight.grad.shape
            )
            print(
                "输出层权重梯度形状：",
                model.输出层.weight.grad.shape
            )
            print(
                "输出层部分梯度：",
                model.输出层.weight.grad[0, :5]
            )

        # ----------------------------------------------------
        # 第 5 步：优化器更新参数
        # Adam 根据梯度和历史信息调整权重、偏置
        # 注意：backward() 计算梯度，step() 更新参数
        # ----------------------------------------------------
        optimizer.step()

        # 累计本批次损失，用于统计本轮平均损失
        本轮损失总和 += loss.item() * len(batch_indices)

    # 计算本轮平均损失
    平均损失 = 本轮损失总和 / 样本数量
    损失记录.append(平均损失)

    # 每 10 轮输出一次训练情况
    if (epoch + 1) % 10 == 0:
        print(
            f"第 {epoch + 1:3d} 轮 | "
            f"平均损失：{平均损失:.6f}"
        )


# ============================================================
# 五、查看训练后的预测结果
# ============================================================

# 切换到评估模式
model.eval()

# 预测阶段不需要计算梯度，节省计算资源
with torch.no_grad():

    # 取出前 5 个样本进行预测
    test_X = X[:5]
    test_y = y[:5]

    # 使用训练好的模型进行前向传播
    test_prediction = model(test_X)

print("\n预测结果：")

for i in range(len(test_X)):
    print(
        f"样本 {i + 1} | "
        f"真实分数：{test_y[i].item():.4f} | "
        f"预测分数：{test_prediction[i].item():.4f}"
    )


# ============================================================
# 六、绘制损失曲线
# ============================================================

plt.figure(figsize=(9, 5))

plt.plot(
    range(1, 训练轮数 + 1),
    损失记录,
    label="Training Loss"
)

plt.xlabel("Epoch")
plt.ylabel("MSE Loss")
plt.title("深度学习训练损失变化")
plt.legend()
plt.grid(True, alpha=0.3)
plt.tight_layout()
plt.show()
